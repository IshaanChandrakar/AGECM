CREATE TABLE telemetry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 unique_key VARCHAR(240) NOT NULL UNIQUE, source_key VARCHAR(240) NOT NULL UNIQUE,
 node_id VARCHAR(32) NOT NULL REFERENCES nodes(id), source VARCHAR(32) NOT NULL,
 schema_version VARCHAR(20) NOT NULL, boot_id VARCHAR(100) NOT NULL, sequence BIGINT NOT NULL,
 channel_id VARCHAR(40), entry_id BIGINT, acquired_at TIMESTAMP WITH TIME ZONE NOT NULL,
 cloud_created_at TIMESTAMP WITH TIME ZONE, received_at TIMESTAMP WITH TIME ZONE NOT NULL,
 uptime_ms BIGINT, tilt DOUBLE PRECISION, displacement DOUBLE PRECISION, vibration DOUBLE PRECISION,
 tilt_rate DOUBLE PRECISION, displacement_velocity DOUBLE PRECISION,
 quality_flags INTEGER NOT NULL, calibrated BOOLEAN NOT NULL, feature_ready BOOLEAN NOT NULL,
 sample_interval_ms INTEGER, report_interval_seconds INTEGER,
 rule_version VARCHAR(60) NOT NULL, state VARCHAR(24) NOT NULL, health VARCHAR(32) NOT NULL,
 CONSTRAINT cloud_identity UNIQUE(channel_id,entry_id),
 CONSTRAINT source_mode CHECK (source IN ('demo','cloud_hardware'))
);
CREATE INDEX telemetry_node_time ON telemetry(node_id,source,acquired_at DESC);
CREATE TABLE alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, node_id VARCHAR(32) NOT NULL REFERENCES nodes(id),
 source VARCHAR(32) NOT NULL, condition VARCHAR(32) NOT NULL, severity VARCHAR(20) NOT NULL,
 trigger_text VARCHAR(500) NOT NULL, first_occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 last_occurred_at TIMESTAMP WITH TIME ZONE NOT NULL, resolved_at TIMESTAMP WITH TIME ZONE,
 record_id BIGINT REFERENCES telemetry(id), rule_version VARCHAR(60) NOT NULL, quality_flags INTEGER NOT NULL
);
CREATE INDEX alerts_time ON alerts(first_occurred_at DESC);
CREATE TABLE ingestion_state (
 node_id VARCHAR(32) PRIMARY KEY REFERENCES nodes(id), channel_id VARCHAR(40), last_entry_id BIGINT NOT NULL DEFAULT 0,
 last_success_at TIMESTAMP WITH TIME ZONE, last_poll_at TIMESTAMP WITH TIME ZONE, status VARCHAR(40) NOT NULL,
 last_error VARCHAR(500), known_gaps INTEGER NOT NULL DEFAULT 0
);
